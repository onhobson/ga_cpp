    /**
     * @brief Performs alternating edge crossover on two permutation sequences.
     * 
     * Builds a child sequence by alternatingly selecting valid edges from the two parent sequences.
     * 
     * @param parent1 The first parent sequence.
     * @param parent2 The second parent sequence.
     * @param rng The random number generator.
     * @return The child sequence generated by alternating edge crossover.
     * 
     * @pre `parent1.size() == parent2.size()`
     * @pre `parent1.size() > 0`
     * @pre `std::ranges::is_permutation(parent1, parent2)`
     */
    template <typename Sequence>
    requires(constraints::Permutable<Sequence> &&
             constraints::HasValueType<Sequence> &&
             constraints::Hashable<typename Sequence::value_type>)
    Sequence alternatingEdge(const Sequence& parent1, const Sequence& parent2, Random& rng)
    {
        const std::size_t size { std::ranges::size(parent1) };

        assert(size == std::ranges::size(parent2) && "Parent sequences must match in size");
        assert(size > 0 && "Parent cannot be size 0");
        assert(debug::arePermutations(parent1, parent2) && "Parents must be permutations");
            
        using Gene = typename Sequence::value_type;

        const auto parent1Begin { std::ranges::begin(parent1) };
        std::unordered_set<Gene, ga::Hash<Gene>> used {};
        Sequence child { parent1 };
        auto childBegin { std::ranges::begin(child) };

        const std::size_t startIndex { rng.template get<std::size_t>(0, size) };
        Gene current { parent1Begin[startIndex] };
        std::size_t childSize {};
        childBegin[childSize++] = current;
        used.insert(current);

        bool parentOne { (rng.get(0, 2)) ? true : false };

        while (childSize < size)
        {
            // Switch the parent used every iteration
            const Sequence& parent { parentOne ? parent1 : parent2 };
            const auto parentBegin { std::ranges::begin(parent) };
            const auto parentEnd { std::ranges::end(parent) };

            const auto currentPosition { std::ranges::find(parent, current) };
            std::vector<Gene> candidates {};

            if (currentPosition != parentEnd)
            {
                // Get next Gene after current
                const std::size_t index { static_cast<std::size_t>(currentPosition - parentBegin) };
                const Gene& next { parentBegin[(index + 1) % size] };
                
                if (!used.contains(next))
                {
                    candidates.push_back(next);
                }
            }

            parentOne = !parentOne;

            if (candidates.empty())
            {
                // Add every Gene not yet used
                for (const Gene& gene : parent1)
                {
                    if (!used.contains(gene))
                    {
                        candidates.push_back(gene);
                    }
                }
            }

            const std::size_t choice { rng.template get<std::size_t>(0, candidates.size()) };
            current = candidates[choice];
            childBegin[childSize++] = current;
            used.insert(current);
        }

        return child;
    }

    /**
     * @brief Performs order crossover on two permutation sequences.
     * 
     * Builds a child sequence by copying a subsequence from the first parent 
     * and filling the remaining positions with genes from the second parent in the order they appear, skipping duplicates.
     * 
     * @param parent1 The first parent sequence.
     * @param parent2 The second parent sequence.
     * @param rng The random number generator.
     * @return The child sequence generated by order crossover.
     * 
     * @pre `parent1.size() == parent2.size()`
     * @pre `parent1.size() >= 2`
     * @pre `std::ranges::is_permutation(parent1, parent2)`
     */
    template <typename Sequence>
    requires(constraints::Permutable<Sequence> &&
             constraints::HasValueType<Sequence> &&
             constraints::Hashable<typename Sequence::value_type>)
    Sequence order(const Sequence& parent1, const Sequence& parent2, Random& rng)
    {
        const std::size_t size { std::ranges::size(parent1) };

        assert(size == std::ranges::size(parent2) && "Parent sequences must match in size");
        assert(size >= 2 && "Parent size must be greater than or equal to 2");
        assert(debug::arePermutations(parent1, parent2) && "Parents must be permutations");

        using Gene = typename Sequence::value_type;

        Sequence child { parent1 };
        std::unordered_set<Gene, ga::Hash<Gene>> used {};

        const auto parent1Begin { std::ranges::begin(parent1) };
        const auto parent2Begin { std::ranges::begin(parent2) };
        auto childBegin { std::ranges::begin(child) };

        // Copy subsequence from parent1        
        const std::size_t firstCut { rng.template get<std::size_t>(0, size - 1) };
        const std::size_t secondCut { rng.template get<std::size_t>(firstCut + 1, size + 1) }; // secondCut is exclusive

        for (std::size_t i { firstCut }; i < secondCut; ++i)
            used.insert(parent1Begin[i]);

        // Copy remaining from parent2 using vertex ordering
        std::size_t childIndex { (secondCut < size) ? secondCut : 0 };
        for (std::size_t offset { 0 }; offset < size; ++offset)
        {
            const Gene& gene { parent2Begin[(secondCut + offset) % size] };

            if (used.contains(gene))
                continue;

            childBegin[childIndex] = gene;
            used.insert(gene);
            childIndex = (childIndex + 1) % size;
        }

        return child;
    }

    /**
     * @brief Performs edge recombination crossover on two permutation sequences.
     * 
     * Builds a child sequence by constructing an adjacency list of edges from both parents and selecting genes based on the fewest neighbors.
     * 
     * @param parent1 The first parent sequence.
     * @param parent2 The second parent sequence.
     * @param rng The random number generator.
     * @return The child sequence generated by edge recombination crossover.
     * 
     * @pre `parent1.size() == parent2.size()`
     * @pre `parent1.size() > 0`
     * @pre Parent sequences contain no duplicates
     * @pre `std::ranges::is_permutation(parent1, parent2)`
     */
    template <typename Sequence>
    requires(constraints::Permutable<Sequence> &&
             constraints::HasValueType<Sequence> &&
             constraints::Hashable<typename Sequence::value_type>)
    Sequence edgeRecombination(const Sequence& parent1, const Sequence& parent2, Random& rng)
    {
        const std::size_t size { std::ranges::size(parent1) };

        assert(size == std::ranges::size(parent2) && "Parent sequences must match in size");
        assert(size > 0 && "Parent cannot be size 0");
        assert(!debug::hasDuplicates(parent1) && "Edge recombination requires no duplicated values in parent sequence");
        assert(debug::arePermutations(parent1, parent2) && "Parents must be permutations");

        using Gene = typename Sequence::value_type;
        const auto parent1Begin { std::ranges::begin(parent1) };

        // Create adjacency lists
        using AdjList = std::unordered_set<Gene, ga::Hash<Gene>>;

        // Maps Gene -> All adjacent genes not yet used
        std::unordered_map<Gene, AdjList, ga::Hash<Gene>> adjPar1;
        std::unordered_map<Gene, AdjList, ga::Hash<Gene>> adjPar2;
        std::unordered_map<Gene, AdjList, ga::Hash<Gene>> adjCombined;

        for (int parentChoice : { 0, 1 })
        {
            // Loop once for each parent's adj list
            const Sequence& parent { (parentChoice) ? parent2 : parent1 };
            auto& adjList { (parentChoice) ? adjPar2 : adjPar1 };

            const auto parentBegin { std::ranges::begin(parent) };

            for (std::size_t i { 0 }; i < size; ++i)
            {
                // Add values to the left and right to adj list
                const std::size_t left { (i + size - 1) % size };
                const std::size_t right { (i + 1) % size };

                adjList[parentBegin[i]].insert({ parentBegin[left], parentBegin[right] });
            }
        }

        // Combine adj lists
        for (const auto& [gene, adjList] : adjPar1)
        {
            adjCombined[gene].insert(adjList.begin(), adjList.end());
            adjCombined[gene].insert(adjPar2[gene].begin(), adjPar2[gene].end());
        }

        Sequence child { parent1 };
        auto childBegin { std::ranges::begin(child) };

        Gene gene { parent1Begin[0] };
        std::unordered_set<Gene, ga::Hash<Gene>> used;
        std::size_t childSize {};
        childBegin[childSize++] = gene;
        used.insert(gene);

        while (childSize < size)
        {
            // Remove gene from all adj lists
            for (auto& [_, adjList] : adjCombined)
            {
                const auto it { adjList.find(gene) };

                if (it != adjList.end())
                    adjList.erase(it);
            }

            if (!adjCombined[gene].empty())
            {
                // Set next to gene neighbor with fewest neighbors
                std::vector<Gene> candidates;
                std::size_t minNeighborSize = std::numeric_limits<std::size_t>::max();

                for (const Gene& neighbor : adjCombined[gene])
                {
                    std::size_t neighborSize { adjCombined[neighbor].size() };

                    if (neighborSize < minNeighborSize)
                    {
                        candidates.clear();
                        candidates.push_back(neighbor);
                        minNeighborSize = neighborSize;
                    }
                    else if (neighborSize == minNeighborSize)
                    {
                        candidates.push_back(neighbor);
                    }
                }

                // Select random candidate
                gene = candidates[ rng.get<std::size_t>(0, candidates.size()) ];
            }
            else
            {
                // Set next to random gene not yet used
                std::vector<Gene> candidates;

                for (const auto& candidate : parent1)
                {
                    if (!used.contains(candidate))
                        candidates.push_back(candidate);
                }

                gene = candidates[ rng.get<std::size_t>(0, candidates.size()) ];
            }

            childBegin[childSize++] = gene;
            used.insert(gene);
        }

        return child;
    }

